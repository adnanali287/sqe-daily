"""Write docs/editorial-approval-batch.md: every content/pages.json entry awaiting approval, exactly as it will publish.

Each entry shows a fingerprint of its text. After the owner approves in chat, record it with
python3 scripts/generate.py --approve <entry> --expect <fingerprint>, which refuses if the text has changed.
"""
import json
from pathlib import Path
import generate

def quote(text):
    return '\n'.join('> ' + line if line else '>' for line in text.strip().split('\n'))

def entry_markdown(label, entry):
    fingerprint = generate.content_hash(entry, generate.APPROVAL_FIELDS)[:12]
    out = [f'### `{label}`', '', f'Fingerprint: `{fingerprint}`', '']
    if label.startswith('sittings.'):
        for key in ['label', 'flk1_date', 'flk1_end', 'flk2_date', 'flk2_end', 'booking_closes', 'results_date', 'source_url']:
            value = entry.get(key)
            out.append(f'- **{key}**: {value if value is not None else "not yet announced"}')
        return '\n'.join(out + [''])
    if label.startswith('subjects.'):
        return '\n'.join(out + [quote(entry['intro']), ''])
    out += [f'- **Title**: {entry["title"]}', f'- **Meta description**: {entry["meta_description"]}', f'- **Heading**: {entry["h1"]}', '', quote(entry['intro']), '']
    for section in entry.get('sections', []):
        out += [f'**{section["heading"]}**', '', quote(section['body']), '']
    if entry.get('sources'):
        out += ['Sources:', ''] + [f'- [{s["label"]}]({s["url"]})' for s in entry['sources']] + ['']
    return '\n'.join(out)

def main():
    data = json.loads((generate.ROOT / 'content/pages.json').read_text())
    pending = [(label, entry) for label, entry in generate.approval_entries(data) if not generate.is_approved(entry)]
    lines = ['# Editorial approval batch', '',
             'Generated by `scripts/approval_batch.py` from `content/pages.json`. Nothing below is published until it is approved.',
             'Approve in chat (all, or by entry). Approval is then recorded with `python3 scripts/generate.py --approve <entry> --expect <fingerprint>`, which refuses if the text has changed since this batch was produced. Any later edit withdraws approval until it is approved again.', '',
             f'Entries awaiting approval: {len(pending)}', '',
             '## Fixed text the generator adds around approved copy', '',
             '- Footer links (only for pages that are live): Practice questions, Exam dates, Guides, Editorial standards.',
             '- Question pages: "How we check questions" link beside "Report an error" once the editorial standards are live; a "Related questions" list.',
             '- Subject pages with an approved introduction: heading "SQE1 {subject} practice questions", a "Rules to remember" section listing each published question\'s rule to remember with a link to the question, and the page title "SQE1 {subject} practice questions (free, with answers)" (shorter for long subject names).',
             '- Practice-questions page: "Practise by paper" (links to the FLK pages and each subject), "Latest questions" (10 most recent), "Guides".',
             '- FLK pages: "{paper} subjects on SQE Daily", "Latest {paper} questions", "Keep practising" (links to the practice-questions page and the other paper).',
             '- Exam dates page: one section per approved sitting listing FLK1, FLK2, booking deadline and results date, with an "SRA source" link.',
             '- Guides: "Keep practising" links to today\'s question and the practice-questions page; a /guides/ index titled "SQE1 guides" with the lead "Practical help with preparing for SQE1, written alongside the daily question."',
             '- Homepage countdown: driven by the next approved sitting; the January 2027 values match what is live today.', '']
    for group, title in [('sittings.', 'Exam sittings'), ('pages.', 'Pages'), ('guides.', 'Guides'), ('subjects.', 'Subject introductions')]:
        items = [entry_markdown(label, entry) for label, entry in pending if label.startswith(group)]
        if items:
            lines += [f'## {title}', ''] + items
    out = generate.ROOT / 'docs/editorial-approval-batch.md'
    out.write_text('\n'.join(lines).rstrip() + '\n', encoding='utf-8')
    print(f'Wrote {out.relative_to(generate.ROOT)} with {len(pending)} entries.')

if __name__ == '__main__':
    main()
