const assert = require('node:assert/strict');
const C = require('../assets/test-core.js');
const raw = require('../content/questions.json');
const now = 1000000;
const pool = raw.filter(q => q.flk === 'FLK1');
const start = options => C.create({bank:raw, paper:'FLK1', now, random:()=>0.42, ...options});
const mini = start({count:10});
assert.equal(mini.questions.length,10);
assert.equal(new Set(mini.sessions.flat()).size,10);
assert.equal(mini.deadline,now + 18*60000);
assert.throws(()=>start({count:170}));
assert.throws(()=>start({bank:pool.slice(0,9)}));
assert.throws(()=>start({subject:'Not a subject'}));
const q = mini.questions[0];
C.answer(mini,q.id,q.answer);
assert.equal(C.results(mini).correct,1);
C.answer(mini,q.id,'Z'); assert.equal(mini.answers[q.id],q.answer);
assert.ok(C.restore(JSON.stringify(mini),raw,now+1000));
const changed = raw.map(x=>x.id===q.id?{...x,answer:x.answer==='A'?'B':'A'}:x);
assert.equal(C.restore(JSON.stringify(mini),changed,now),null);
assert.equal(C.restore('{broken',raw),null);
assert.equal(C.restore(JSON.stringify({...mini,deadline:null}),raw,now),null);
C.reconcile(mini,mini.deadline);
assert.equal(mini.status,'results');
assert.equal(C.results(mini).unanswered,9);
C.answer(mini,q.id,'E'); assert.equal(mini.answers[q.id],q.answer);
const untimed=start({timed:false,count:20});
C.reconcile(untimed,now+1e10); assert.equal(untimed.status,'active');
// Synthetic, non-published fixtures exercise full papers without inventing legal content.
const fixtures=Array.from({length:170},(_,i)=>({...raw[0],id:`fixture-${i}`}));
const mock={id:'fixture',title:'Fixture paper',paper:'FLK1',law_cutoff:'2026-09-11',sessions:[fixtures.slice(0,85).map(q=>q.id),fixtures.slice(85).map(q=>q.id)]};
const full=C.create({bank:fixtures,paper:'FLK1',mock,now});
const shuffled=C.create({bank:fixtures,paper:'FLK1',mock,now,random:()=>0});
assert.notDeepEqual(shuffled.sessions[0],mock.sessions[0]);
assert.deepEqual([...shuffled.sessions[0]].sort(),[...mock.sessions[0]].sort());
assert.deepEqual([...shuffled.sessions[1]].sort(),[...mock.sessions[1]].sort());
assert.equal(full.deadline,now+C.SESSION_MS);
assert.throws(()=>C.create({bank:fixtures,paper:'FLK2',mock,now}));
assert.throws(()=>C.create({bank:fixtures,paper:'FLK1',mock:{...mock,sessions:[mock.sessions[0],mock.sessions[0]]},now}));
C.answer(full,fixtures[85].id,'A'); assert.equal(full.answers[fixtures[85].id],undefined);
full.flags[fixtures[0].id]=true;
C.reconcile(full,now+C.SESSION_MS);
assert.equal(full.status,'break');
assert.equal(C.advance(full,full.breakUntil-1),false);
C.answer(full,fixtures[0].id,'A'); assert.equal(full.answers[fixtures[0].id],undefined);
const resumed=C.restore(JSON.stringify(full),fixtures,now+C.SESSION_MS+C.BREAK_MS+1000);
assert.equal(resumed.session,1); assert.equal(resumed.status,'active');
assert.equal(resumed.deadline,now+2*C.SESSION_MS+C.BREAK_MS);
C.answer(resumed,fixtures[0].id,'A'); assert.equal(resumed.answers[fixtures[0].id],undefined);
C.reconcile(resumed,now+2*C.SESSION_MS+C.BREAK_MS+1);
assert.equal(resumed.status,'results');
assert.equal(C.results(resumed).total,170);
const longClosed=C.restore(JSON.stringify(full),fixtures,now+3*C.SESSION_MS+C.BREAK_MS);
assert.equal(longClosed.status,'results','a closed tab cannot pause session 2');
const practice=C.create({bank:fixtures,paper:'FLK1',mock,now,timed:false});
C.finish(practice,now); assert.equal(C.advance(practice,now),true);
console.log('PASS: mini pools, unique sampling, answer guards, scoring, corrupt/corrected saves, deadlines, session locks, break and offline catch-up');
